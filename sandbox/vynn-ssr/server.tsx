import fs from "node:fs";

import express, { Request, Response } from "express";
import { createServer as createViteServer, ViteDevServer } from "vite";
import { toWebRequest } from "vynn/server/node";

const isDev = process.env.NODE_ENV === "development";
const PORT = isDev ? 5173 : 4173;

const start = Date.now();
const app = express();
let vite: ViteDevServer | undefined;

if (isDev) {
  vite = await createViteServer({
    server: { middlewareMode: true },
    appType: "custom",
  });

  app.use(vite.middlewares);
} else {
  const compression = (await import("compression")).default;
  const sirv = (await import("sirv")).default;
  app.use(compression());
  app.use("/", sirv("./dist/client", { extensions: [] }));
}

type ServerEntry = {
  render: (
    url: string,
  ) => Promise<string> | ReadableStream<Uint8Array<ArrayBufferLike>>;
  handleServerFunctionRequest: (
    request: globalThis.Request,
  ) => Promise<globalThis.Response | null>;
};

let productionServerEntry: Promise<ServerEntry> | undefined;

function getProductionServerEntry(): Promise<ServerEntry> {
  // @ts-expect-error Generated by the production SSR build.
  productionServerEntry ??= import("./dist/server/entry-server.js");
  return productionServerEntry;
}

function getWriteChunk(res: Response) {
  return async function writeChunk(
    chunk: Uint8Array<ArrayBufferLike> | string,
  ) {
    const canContinue = res.write(chunk);
    res.flush?.();

    if (!canContinue) {
      await new Promise<void>((resolve) => {
        res.once("drain", resolve);
      });
    }
  };
}

app.use(
  "/__vynn/server-function",
  async (req: Request, res: Response, next) => {
    if (isDev) return next();

    const entry = await getProductionServerEntry();
    const request = toWebRequest(req, {
      url: req.originalUrl,
      origin: `${req.protocol}://${req.get("host") ?? "localhost"}`,
    });
    const response = await entry.handleServerFunctionRequest(request);

    if (!response || !response.body) {
      return next();
    }

    const writeChunk = getWriteChunk(res);
    const reader = response.body.getReader();

    while (!res.destroyed) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value) continue;

      await writeChunk(value);
    }

    res.end();
  },
);

app.use("*all", async (req: Request, res: Response, next) => {
  if (req.originalUrl.includes(".")) {
    next();
    return;
  }

  try {
    let template: string;
    let render: (
      request: globalThis.Request,
    ) => Promise<string> | ReadableStream<Uint8Array<ArrayBufferLike>>;
    const request = toWebRequest(req, {
      url: req.originalUrl,
      origin: `${req.protocol}://${req.get("host") ?? "localhost"}`,
    });

    if (isDev && vite) {
      template = fs.readFileSync("./index.html", "utf-8");
      template = (await vite.transformIndexHtml(req.originalUrl, template))
        .replace(/>\s+</g, "><")
        .trim();

      render = (await vite.ssrLoadModule("/src/entry-server.tsx")).render;
    } else {
      template = fs
        .readFileSync("./dist/client/index.html", "utf-8")
        .replace(/>\s+</g, "><")
        .trim();
      // @ts-expect-error dist file
      render = (await import("./dist/server/entry-server.js")).render;
    }

    const stream = await render(request);

    const [head, tail] = template.split("<!--ssr-outlet-->");

    res.status(200).set({
      "Content-Type": "text/html; charset=utf-8",
    });

    const writeChunk = getWriteChunk(res);

    await writeChunk(head);

    for await (const chunk of stream) {
      await writeChunk(chunk);
    }

    await writeChunk(tail);
    res.end();
  } catch (e) {
    if (e instanceof Error && vite) {
      vite.ssrFixStacktrace(e);
    }
    next(e);
  }
});

app.listen(PORT, () => {
  console.clear();
  const elapsed = Date.now() - start;

  console.log(`\n  VYNN v0.0.0  ready in ${elapsed} ms\n`);
  console.log(`  ➜  Local:   \x1b[36mhttp://localhost:${PORT}/\x1b[0m`);
  console.log(`  ➜  Network: use --host to expose`);
  console.log(`  ➜  press h + enter to show help`);
});
