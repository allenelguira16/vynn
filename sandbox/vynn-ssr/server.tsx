import fs from "node:fs";

import express, { type Request, type Response } from "express";
import { createServer as createViteServer, type ViteDevServer } from "vite";
import {
  getSsrHead,
  getSsrModuleIds,
  injectSsrPreloadLinks,
  renderSsrPreloadLinks,
  runWithSsrContext,
  type SsrClientManifest,
} from "vynn/server";
import { toWebRequest } from "vynn/server/node";

const isDev = process.env.NODE_ENV === "development";
const port = isDev ? 5173 : 4173;
const app = express();
const startedAt = Date.now();

type Render = (
  request: globalThis.Request,
) => string | Promise<string> | ReadableStream<Uint8Array<ArrayBufferLike>>;

type ServerEntry = {
  render: Render;
  handleServerFunctionRequest: (
    request: globalThis.Request,
  ) => Promise<globalThis.Response | null>;
};

const manifestPath = new URL(
  "./dist/client/.vite/ssr-manifest.json",
  import.meta.url,
);

const ssrManifest: SsrClientManifest | null = isDev
  ? null
  : (() => {
      if (!fs.existsSync(manifestPath)) {
        throw new Error(
          "[vynn-ssr] Missing dist/client/.vite/ssr-manifest.json. Run `pnpm build:client` before starting the production server.",
        );
      }
      return JSON.parse(
        fs.readFileSync(manifestPath, "utf8"),
      ) as SsrClientManifest;
    })();

let vite: ViteDevServer | undefined;
let productionEntry: Promise<ServerEntry> | undefined;

function getProductionEntry() {
  // @ts-expect-error Generated by the production SSR build.
  return (productionEntry ??= import("./dist/server/entry-server.js"));
}

function toRequest(req: Request) {
  return toWebRequest(req, {
    url: req.originalUrl,
    origin: `${req.protocol}://${req.get("host") ?? "localhost"}`,
  });
}

async function writeStream(
  res: Response,
  stream: string | ReadableStream<Uint8Array<ArrayBufferLike>>,
  beforeChunk?: () => Promise<void>,
) {
  const write = async (chunk: string | Uint8Array<ArrayBufferLike>) => {
    const canContinue = res.write(chunk);
    res.flush?.();
    if (!canContinue) {
      await new Promise<void>((resolve) => res.once("drain", resolve));
    }
  };

  if (typeof stream === "string") {
    await beforeChunk?.();
    return write(stream);
  }

  const reader = stream.getReader();
  try {
    while (!res.destroyed) {
      const { done, value } = await reader.read();
      if (done) break;
      await beforeChunk?.();
      await write(value);
    }

    // A final async boundary can discover preloadable modules after the
    // last body chunk has been read.
    if (!res.destroyed) await beforeChunk?.();
  } finally {
    reader.releaseLock();
  }
}

async function loadPage(url: string) {
  const path = isDev ? "./index.html" : "./dist/client/index.html";
  let template = fs.readFileSync(path, "utf8");
  let render: Render;

  if (isDev && vite) {
    const [transformed, entry] = await Promise.all([
      vite.transformIndexHtml(url, template),
      vite.ssrLoadModule("/src/entry-server.tsx") as Promise<
        Pick<ServerEntry, "render">
      >,
    ]);
    template = transformed;
    render = entry.render;
  } else {
    render = (await getProductionEntry()).render;
  }

  return { template: template.replace(/>\s+</g, "><").trim(), render };
}

async function handleServerFunction(
  req: Request,
  res: Response,
  next: (error?: unknown) => void,
) {
  if (isDev) return next();

  const response = (await (
    await getProductionEntry()
  ).handleServerFunctionRequest(toRequest(req))) as globalThis.Response;
  if (!response) return next();

  res.status(response.status);
  response.headers.forEach((value, key) => res.setHeader(key, value));
  if (response.body) await writeStream(res, response.body);
  res.end();
}

async function handlePageRequest(
  req: Request,
  res: Response,
  next: (error?: unknown) => void,
) {
  if (req.originalUrl.includes(".")) return next();

  try {
    await runWithSsrContext(async () => {
    const { template, render } = await loadPage(req.originalUrl);

    // Capture the live set before awaiting; nested lazy boundaries can register
    // more modules while the stream is being consumed.
    const rendered = render(toRequest(req));
    const streaming = rendered instanceof ReadableStream;
    const moduleIds = getSsrModuleIds();
    // Async SSR is complete before the document shell is sent. Streaming SSR
    // emits late head updates through the Vynn stream patch runtime.
    const html = typeof rendered === "string" || streaming ? rendered : await rendered;
    const headHtml = getSsrHead();
    const seen = new Set<string>();
    const getPreloadLinks = () =>
      renderSsrPreloadLinks(moduleIds, ssrManifest, {
        base: "/",
        dev: isDev,
        exclude: seen,
      });
    const headOutlet = "<!--ssr-head-->";
    const outlet = "<!--ssr-outlet-->";
    if (!template.includes(headOutlet)) {
      throw new Error(`Missing ${headOutlet} in the HTML template.`);
    }

    const document = template.replace(
      headOutlet,
      headHtml + getPreloadLinks(),
    );
    const index = document.indexOf(outlet);
    if (index < 0) {
      throw new Error(`Missing ${outlet} in the HTML template.`);
    }

    res.status(200).type("html");
    await writeStream(res, document.slice(0, index));
    await writeStream(res, html, async () => {
      const links = getPreloadLinks();
      if (links) await writeStream(res, injectSsrPreloadLinks(links));
    });
    await writeStream(res, document.slice(index + outlet.length));
    res.end();
    });
  } catch (error) {
    if (error instanceof Error && vite) vite.ssrFixStacktrace(error);
    next(error);
  }
}

if (isDev) {
  vite = await createViteServer({
    server: { middlewareMode: true },
    appType: "custom",
  });
  app.use(vite.middlewares);
} else {
  const compression = (await import("compression")).default;
  const sirv = (await import("sirv")).default;
  app.use(compression(), sirv("./dist/client", { extensions: [] }));
}

app.use("/__vynn/server-function", handleServerFunction);
app.use("*all", handlePageRequest);

app.listen(port, () => {
  console.clear();
  console.log(`\n  VYNN v0.0.0  ready in ${Date.now() - startedAt} ms\n`);
  console.log(`  ➜  Local:   \x1b[36mhttp://localhost:${port}/\x1b[0m`);
  console.log("  ➜  Network: use --host to expose");
  console.log("  ➜  press h + enter to show help");
});
